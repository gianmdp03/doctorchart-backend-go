ALTER TABLE public.clinics ADD CONSTRAINT clinics_id_workspace_key UNIQUE (id,workspace_id);
CREATE TABLE public.bookings (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 workspace_id bigint NOT NULL REFERENCES public.doctor_workspaces(id) ON DELETE RESTRICT,
 clinic_id bigint NOT NULL,
 patient_id bigint REFERENCES public.patients(id) ON DELETE RESTRICT,
 start_at timestamptz NOT NULL,
 end_at timestamptz NOT NULL,
 status varchar(20) NOT NULL DEFAULT 'CONFIRMED' CHECK (status IN ('CONFIRMED','CHECKED_IN','COMPLETED','NO_SHOW','CANCELLED')),
 version bigint NOT NULL DEFAULT 1 CHECK (version>0),
 contact_name varchar(160) NOT NULL CHECK (length(btrim(contact_name))>0),
 contact_phone varchar(80) NOT NULL DEFAULT '',
 created_at timestamptz NOT NULL DEFAULT clock_timestamp(),
 updated_at timestamptz NOT NULL DEFAULT clock_timestamp(),
 CONSTRAINT bookings_clinic_owner_fk FOREIGN KEY (clinic_id,workspace_id) REFERENCES public.clinics(id,workspace_id) ON DELETE RESTRICT,
 CONSTRAINT bookings_interval_check CHECK (isfinite(start_at) AND isfinite(end_at) AND start_at<end_at AND end_at-start_at<=interval '8 hours'),
 CONSTRAINT bookings_owner_interval_exclusion EXCLUDE USING gist (
  numrange(workspace_id::numeric,workspace_id::numeric,'[]') WITH &&,
  tstzrange(start_at,end_at,'[)') WITH &&
 ) WHERE (status<>'CANCELLED')
);
CREATE INDEX bookings_workspace_start_idx ON public.bookings(workspace_id,start_at,id);
CREATE INDEX bookings_patient_idx ON public.bookings(patient_id) WHERE patient_id IS NOT NULL;

CREATE FUNCTION public.validate_booking_owner_transition() RETURNS trigger
LANGUAGE plpgsql SET search_path=pg_catalog AS $$
BEGIN
 IF NEW.patient_id IS NOT NULL AND NOT EXISTS (
  SELECT 1 FROM public.patients p JOIN public.doctor_workspaces w ON w.user_id=p.user_id
  WHERE p.id=NEW.patient_id AND w.id=NEW.workspace_id
 ) THEN
  RAISE EXCEPTION 'booking patient ownership mismatch' USING ERRCODE='23514',CONSTRAINT='bookings_patient_owner_check';
 END IF;
 IF TG_OP='UPDATE' THEN
  IF NEW.id<>OLD.id OR NEW.workspace_id<>OLD.workspace_id OR NEW.created_at<>OLD.created_at OR NEW.version<>OLD.version+1 THEN
   RAISE EXCEPTION 'booking immutable identity or version mismatch' USING ERRCODE='23514',CONSTRAINT='bookings_identity_version_check';
  END IF;
  IF NEW.patient_id IS DISTINCT FROM OLD.patient_id OR NEW.contact_name<>OLD.contact_name OR NEW.contact_phone<>OLD.contact_phone THEN
   RAISE EXCEPTION 'booking contact is immutable in M4' USING ERRCODE='23514',CONSTRAINT='bookings_contact_check';
  END IF;
  IF (NEW.start_at,NEW.end_at,NEW.clinic_id) IS DISTINCT FROM (OLD.start_at,OLD.end_at,OLD.clinic_id)
     AND (OLD.status<>'CONFIRMED' OR NEW.status<>'CONFIRMED') THEN
   RAISE EXCEPTION 'booking cannot be rescheduled in current state' USING ERRCODE='23514',CONSTRAINT='bookings_transition_check';
  END IF;
  IF NEW.status<>OLD.status AND NOT (
   (OLD.status='CONFIRMED' AND NEW.status IN ('CHECKED_IN','NO_SHOW','CANCELLED'))
   OR (OLD.status='CHECKED_IN' AND NEW.status IN ('COMPLETED','CANCELLED'))
  ) THEN
   RAISE EXCEPTION 'invalid booking status transition' USING ERRCODE='23514',CONSTRAINT='bookings_transition_check';
  END IF;
 END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER bookings_validate_owner_transition BEFORE INSERT OR UPDATE ON public.bookings
 FOR EACH ROW EXECUTE FUNCTION public.validate_booking_owner_transition();

CREATE TABLE public.booking_events (
 booking_id bigint NOT NULL REFERENCES public.bookings(id) ON DELETE RESTRICT,
 version bigint NOT NULL CHECK(version>0),
 kind varchar(24) NOT NULL CHECK(kind IN ('CREATED','STATUS_CHANGED','RESCHEDULED')),
 actor_id varchar(100) NOT NULL CHECK(length(actor_id)>0),
 occurred_at timestamptz NOT NULL DEFAULT clock_timestamp(),
 before_document jsonb,
 after_document jsonb NOT NULL CHECK(jsonb_typeof(after_document)='object'),
 PRIMARY KEY(booking_id,version)
);
CREATE TABLE public.booking_idempotency (
 workspace_id bigint NOT NULL REFERENCES public.doctor_workspaces(id) ON DELETE RESTRICT,
 key varchar(128) NOT NULL CHECK(length(key)>=16),
 request_sha256 varchar(64) NOT NULL CHECK(request_sha256 ~ '^[0-9a-f]{64}$'),
 booking_id bigint NOT NULL REFERENCES public.bookings(id) ON DELETE RESTRICT,
 response_status integer NOT NULL CHECK(response_status IN (200,201)),
 response_document jsonb NOT NULL CHECK(jsonb_typeof(response_document)='object'),
 created_at timestamptz NOT NULL DEFAULT clock_timestamp(),
 PRIMARY KEY(workspace_id,key)
);

