CREATE TABLE booking_confirmation_access (
 booking_id bigint PRIMARY KEY REFERENCES bookings(id),
 token_hash char(64) NOT NULL UNIQUE,
 encrypted_code bytea NOT NULL,
 expires_at timestamptz NOT NULL,
 revoked_at timestamptz,
 created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE staff_email_recovery (
 id uuid PRIMARY KEY,
 account_id uuid NOT NULL REFERENCES staff_accounts(id),
 token_hash char(64) NOT NULL UNIQUE,
 expires_at timestamptz NOT NULL,
 consumed_at timestamptz,
 created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX staff_email_recovery_account_idx ON staff_email_recovery(account_id);
CREATE TABLE notification_outbox (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 dedup_key varchar(160) NOT NULL UNIQUE,
 kind varchar(32) NOT NULL CHECK(kind IN ('BOOKING_CONFIRMED','BOOKING_CANCELLED','BOOKING_RESCHEDULED','BOOKING_REMINDER','STAFF_INVITATION','STAFF_RECOVERY')),
 booking_id bigint REFERENCES bookings(id),
 booking_version bigint,
 access_id uuid REFERENCES staff_access(id),
 recovery_id uuid REFERENCES staff_email_recovery(id),
 payload bytea NOT NULL,
 due_at timestamptz NOT NULL,
 state varchar(16) NOT NULL DEFAULT 'PENDING' CHECK(state IN ('PENDING','PROCESSING','SENT','OBSOLETE','DEAD')),
 attempts integer NOT NULL DEFAULT 0 CHECK(attempts>=0),
 lease_until timestamptz,
 lease_id uuid,
 last_code varchar(48),
 created_at timestamptz NOT NULL DEFAULT now(),
 sent_at timestamptz,
 CHECK ((booking_id IS NOT NULL AND booking_version IS NOT NULL AND access_id IS NULL AND recovery_id IS NULL) OR (booking_id IS NULL AND booking_version IS NULL AND ((access_id IS NOT NULL AND recovery_id IS NULL) OR (access_id IS NULL AND recovery_id IS NOT NULL))))
);
CREATE INDEX notification_outbox_due_idx ON notification_outbox(due_at,id) WHERE state IN ('PENDING','PROCESSING');
CREATE INDEX notification_outbox_booking_idx ON notification_outbox(booking_id,booking_version);
