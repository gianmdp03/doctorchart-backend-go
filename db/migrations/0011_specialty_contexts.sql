-- M1 specialties: move each existing clinical configuration without changing
-- workspace identities or administrative/clinical resource relationships.
CREATE TABLE public.doctor_specialty_contexts (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    workspace_id bigint NOT NULL REFERENCES public.doctor_workspaces(id) ON DELETE RESTRICT,
    specialty_id bigint NOT NULL REFERENCES public.specialties(id) ON DELETE RESTRICT,
    definition jsonb,
    draft_definition jsonb,
    source_wizard_version bigint CHECK (source_wizard_version > 0),
    draft_source_wizard_version bigint CHECK (draft_source_wizard_version > 0),
    version bigint NOT NULL CHECK (version >= 0),
    current_step_key varchar(96) NOT NULL,
    onboarding_completed boolean NOT NULL,
    created_at timestamptz(6) NOT NULL,
    updated_at timestamptz(6) NOT NULL,
    CONSTRAINT doctor_specialty_contexts_workspace_specialty_key UNIQUE (workspace_id, specialty_id),
    -- Deliberate M1 gate: remove only when multiple contexts are authorized.
    CONSTRAINT doctor_specialty_contexts_single_context_key UNIQUE (workspace_id)
);

INSERT INTO public.doctor_specialty_contexts (
    workspace_id,specialty_id,definition,draft_definition,source_wizard_version,
    draft_source_wizard_version,version,current_step_key,onboarding_completed,created_at,updated_at
)
SELECT id,specialty_id,definition,draft_definition,source_wizard_version,
       draft_source_wizard_version,version,current_step_key,onboarding_completed,created_at,updated_at
FROM public.doctor_workspaces ORDER BY id;

-- The values above now have one owner. No permanent shadow configuration.
ALTER TABLE public.doctor_workspaces
    DROP COLUMN specialty_id,
    DROP COLUMN definition,
    DROP COLUMN draft_definition,
    DROP COLUMN source_wizard_version,
    DROP COLUMN draft_source_wizard_version,
    DROP COLUMN current_step_key,
    DROP COLUMN onboarding_completed;
