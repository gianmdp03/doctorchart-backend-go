-- Expand only: local identities never reference or impersonate Supabase users.
ALTER TABLE clinics ADD CONSTRAINT clinics_id_workspace_unique UNIQUE(id,workspace_id);
CREATE TABLE staff_accounts (
 id uuid PRIMARY KEY,
 email varchar(254) NOT NULL UNIQUE CHECK(email=lower(btrim(email))),
 name varchar(160) NOT NULL CHECK(length(name)>0),
 password_hash text NOT NULL,
 recovery_hash char(64) NOT NULL,
 created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE staff_access (
 id uuid PRIMARY KEY,
 workspace_id bigint NOT NULL REFERENCES doctor_workspaces(id),
 account_id uuid REFERENCES staff_accounts(id),
 email varchar(254) NOT NULL CHECK(email=lower(btrim(email))),
 name varchar(160) NOT NULL CHECK(length(name)>0),
 permissions text[] NOT NULL CHECK(permissions <@ ARRAY['view','create','cancel','reschedule','status']::text[] AND 'view'=ANY(permissions)),
 active boolean NOT NULL DEFAULT true,
 version bigint NOT NULL DEFAULT 1 CHECK(version>0),
 UNIQUE(workspace_id,email),
 UNIQUE(id,workspace_id)
);
CREATE INDEX staff_access_account_idx ON staff_access(account_id) WHERE active;
CREATE TABLE staff_access_clinics (
 access_id uuid NOT NULL,
 workspace_id bigint NOT NULL,
 clinic_id bigint NOT NULL,
 PRIMARY KEY(access_id,clinic_id),
 FOREIGN KEY(access_id,workspace_id) REFERENCES staff_access(id,workspace_id),
 FOREIGN KEY(clinic_id,workspace_id) REFERENCES clinics(id,workspace_id)
);
CREATE TABLE staff_invitations (
 token_hash char(64) PRIMARY KEY,
 access_id uuid NOT NULL REFERENCES staff_access(id),
 expires_at timestamptz NOT NULL,
 consumed_at timestamptz,
 created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX staff_invitations_access_idx ON staff_invitations(access_id);
CREATE TABLE staff_sessions (
 token_hash char(64) PRIMARY KEY,
 account_id uuid NOT NULL REFERENCES staff_accounts(id),
 expires_at timestamptz NOT NULL,
 revoked_at timestamptz,
 created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX staff_sessions_account_idx ON staff_sessions(account_id);
CREATE TABLE staff_rate_windows (
 key char(64) NOT NULL,
 bucket timestamptz NOT NULL,
 attempts integer NOT NULL CHECK(attempts>0),
 PRIMARY KEY(key,bucket)
);
CREATE TABLE staff_security_events (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 account_id uuid REFERENCES staff_accounts(id),
 access_id uuid REFERENCES staff_access(id),
 kind varchar(48) NOT NULL,
 occurred_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX staff_security_events_account_idx ON staff_security_events(account_id,occurred_at);
