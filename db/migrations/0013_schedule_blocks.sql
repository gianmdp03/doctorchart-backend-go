-- A schedule remains administrative and unique per clinic. Blocks own duration
-- and clinical context; JSON below is consumed once, never retained as a mirror.
DO $$ BEGIN
 IF EXISTS(SELECT 1 FROM clinic_schedules s JOIN clinics cl ON cl.id=s.clinic_id
 LEFT JOIN doctor_specialty_contexts c ON c.workspace_id=cl.workspace_id WHERE c.id IS NULL) THEN
  RAISE EXCEPTION 'M3: schedule owner has no specialty context' USING ERRCODE='23514';
 END IF;
END $$;
ALTER TABLE clinic_schedules ADD COLUMN workspace_id bigint;
UPDATE clinic_schedules s SET workspace_id=c.workspace_id FROM clinics c WHERE c.id=s.clinic_id;
ALTER TABLE clinic_schedules ALTER COLUMN workspace_id SET NOT NULL,
 ADD CONSTRAINT clinic_schedules_clinic_workspace_key UNIQUE(clinic_id,workspace_id),
 ADD CONSTRAINT clinic_schedules_owner_fkey FOREIGN KEY(clinic_id,workspace_id) REFERENCES clinics(id,workspace_id) ON DELETE RESTRICT;

CREATE TABLE schedule_exceptions (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 clinic_id bigint NOT NULL,
 workspace_id bigint NOT NULL,
 from_date date NOT NULL CHECK(from_date BETWEEN DATE '0001-01-01' AND DATE '9999-12-31'),
 through_date date NOT NULL CHECK(through_date>=from_date AND through_date<=DATE '9999-12-31'),
 -- Preserve legacy labels byte-for-byte; the HTTP limit counts trimmed runes.
 label text NOT NULL,
 CONSTRAINT schedule_exceptions_id_clinic_workspace_key UNIQUE(id,clinic_id,workspace_id),
 CONSTRAINT schedule_exceptions_schedule_fkey FOREIGN KEY(clinic_id,workspace_id) REFERENCES clinic_schedules(clinic_id,workspace_id) ON DELETE RESTRICT,
 CONSTRAINT schedule_exceptions_no_overlap EXCLUDE USING gist
 (int8range(clinic_id,clinic_id,'[]') WITH &&,daterange(from_date,through_date,'[]') WITH &&) DEFERRABLE INITIALLY DEFERRED
);
CREATE TABLE schedule_blocks (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 clinic_id bigint NOT NULL,
 workspace_id bigint NOT NULL,
 specialty_context_id bigint NOT NULL,
 weekday integer CHECK(weekday BETWEEN 1 AND 7),
 exception_id bigint,
 start_minute integer NOT NULL CHECK(start_minute BETWEEN 0 AND 1439),
 end_minute integer NOT NULL CHECK(end_minute BETWEEN 1 AND 1440 AND end_minute>start_minute),
 slot_minutes integer NOT NULL CHECK(slot_minutes BETWEEN 5 AND 480),
 CONSTRAINT schedule_blocks_kind_check CHECK((weekday IS NULL)<>(exception_id IS NULL)),
 CONSTRAINT schedule_blocks_schedule_fkey FOREIGN KEY(clinic_id,workspace_id) REFERENCES clinic_schedules(clinic_id,workspace_id) ON DELETE RESTRICT,
 CONSTRAINT schedule_blocks_context_fkey FOREIGN KEY(specialty_context_id,workspace_id) REFERENCES doctor_specialty_contexts(id,workspace_id) ON DELETE RESTRICT,
 CONSTRAINT schedule_blocks_exception_fkey FOREIGN KEY(exception_id,clinic_id,workspace_id) REFERENCES schedule_exceptions(id,clinic_id,workspace_id) ON DELETE RESTRICT,
 CONSTRAINT schedule_blocks_weekly_no_overlap EXCLUDE USING gist
 (int8range(clinic_id,clinic_id,'[]') WITH &&,int4range(weekday,weekday,'[]') WITH &&,int4range(start_minute,end_minute,'[)') WITH &&)
 WHERE(exception_id IS NULL) DEFERRABLE INITIALLY DEFERRED,
 CONSTRAINT schedule_blocks_exception_no_overlap EXCLUDE USING gist
 (int8range(exception_id,exception_id,'[]') WITH &&,int4range(start_minute,end_minute,'[)') WITH &&)
 WHERE(exception_id IS NOT NULL) DEFERRABLE INITIALLY DEFERRED
);
CREATE INDEX schedule_blocks_clinic_idx ON schedule_blocks(clinic_id,weekday,start_minute,id);
CREATE INDEX schedule_blocks_context_idx ON schedule_blocks(specialty_context_id,id);
CREATE INDEX schedule_blocks_exception_idx ON schedule_blocks(exception_id);

-- Parse/validate each legacy value strictly before removing it. Closures get
-- exception identities even when they have no blocks.
DO $$
DECLARE s record; d jsonb; e jsonb; r jsonb; eid bigint; cid bigint; a integer; b integer;
BEGIN
 FOR s IN SELECT * FROM clinic_schedules ORDER BY clinic_id LOOP
  SELECT id INTO STRICT cid FROM doctor_specialty_contexts WHERE workspace_id=s.workspace_id;
  FOR d IN SELECT value FROM jsonb_array_elements(s.weekly) LOOP
   IF jsonb_typeof(d->'ranges') IS DISTINCT FROM 'array' OR jsonb_typeof(d->'weekday') IS DISTINCT FROM 'number' OR (d->>'weekday') !~ '^[1-7]$' OR jsonb_array_length(d->'ranges')>16 THEN
    RAISE EXCEPTION 'M3: invalid legacy weekday';
   END IF;
   FOR r IN SELECT value FROM jsonb_array_elements(d->'ranges') LOOP
    IF (r->>'start') IS NULL OR (r->>'end') IS NULL OR (r->>'start') !~ '^([01][0-9]|2[0-3]):[0-5][0-9]$' OR (r->>'end') !~ '^(([01][0-9]|2[0-3]):[0-5][0-9]|24:00)$' THEN RAISE EXCEPTION 'M3: invalid legacy time'; END IF;
    a:=split_part(r->>'start',':',1)::int*60+split_part(r->>'start',':',2)::int;
    b:=split_part(r->>'end',':',1)::int*60+split_part(r->>'end',':',2)::int;
    INSERT INTO schedule_blocks(clinic_id,workspace_id,specialty_context_id,weekday,start_minute,end_minute,slot_minutes) VALUES(s.clinic_id,s.workspace_id,cid,(d->>'weekday')::int,a,b,s.slot_minutes);
   END LOOP;
  END LOOP;
  IF EXISTS(SELECT 1 FROM jsonb_array_elements(s.weekly) x GROUP BY x->>'weekday' HAVING count(*)>1) THEN RAISE EXCEPTION 'M3: repeated legacy weekday'; END IF;
  FOR e IN SELECT value FROM jsonb_array_elements(s.exceptions) LOOP
   IF jsonb_typeof(e->'ranges') IS DISTINCT FROM 'array' OR jsonb_array_length(e->'ranges')>16 OR jsonb_typeof(e->'label') IS DISTINCT FROM 'string' OR (e->>'from') IS NULL OR (e->>'through') IS NULL OR (e->>'from') !~ '^[0-9]{4}-[0-9]{2}-[0-9]{2}$' OR (e->>'through') !~ '^[0-9]{4}-[0-9]{2}-[0-9]{2}$' THEN RAISE EXCEPTION 'M3: invalid legacy exception'; END IF;
   INSERT INTO schedule_exceptions(clinic_id,workspace_id,from_date,through_date,label) VALUES(s.clinic_id,s.workspace_id,(e->>'from')::date,(e->>'through')::date,e->>'label') RETURNING id INTO eid;
   FOR r IN SELECT value FROM jsonb_array_elements(e->'ranges') LOOP
    IF (r->>'start') IS NULL OR (r->>'end') IS NULL OR (r->>'start') !~ '^([01][0-9]|2[0-3]):[0-5][0-9]$' OR (r->>'end') !~ '^(([01][0-9]|2[0-3]):[0-5][0-9]|24:00)$' THEN RAISE EXCEPTION 'M3: invalid legacy time'; END IF;
    a:=split_part(r->>'start',':',1)::int*60+split_part(r->>'start',':',2)::int;
    b:=split_part(r->>'end',':',1)::int*60+split_part(r->>'end',':',2)::int;
    INSERT INTO schedule_blocks(clinic_id,workspace_id,specialty_context_id,exception_id,start_minute,end_minute,slot_minutes) VALUES(s.clinic_id,s.workspace_id,cid,eid,a,b,s.slot_minutes);
   END LOOP;
  END LOOP;
 END LOOP;
END $$;
SET CONSTRAINTS schedule_exceptions_no_overlap,schedule_blocks_weekly_no_overlap,schedule_blocks_exception_no_overlap IMMEDIATE;
ALTER TABLE clinic_schedules DROP COLUMN slot_minutes,DROP COLUMN weekly,DROP COLUMN exceptions;
