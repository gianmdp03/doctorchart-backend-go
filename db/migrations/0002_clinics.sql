-- Schema 1 -> 2. Owned by db.Ensure's transaction and advisory lock.
-- Published baseline and all clinical tables remain unchanged.
CREATE TABLE public.app_schema_migrations (
    version integer PRIMARY KEY CHECK (version > 1),
    sql_sha256 character(64) NOT NULL CHECK (sql_sha256 ~ '^[0-9a-f]{64}$'),
    previous_catalog_sha256 character(64) NOT NULL CHECK (previous_catalog_sha256 ~ '^[0-9a-f]{64}$'),
    catalog_sha256 character(64) NOT NULL CHECK (catalog_sha256 ~ '^[0-9a-f]{64}$'),
    applied_at timestamp with time zone NOT NULL DEFAULT now()
);

-- pg_timezone_names is PostgreSQL's installed IANA database. Reject offset-only
-- values and legacy abbreviations; UTC and named regions are accepted.
CREATE FUNCTION public.is_iana_timezone(value text) RETURNS boolean
LANGUAGE sql STABLE STRICT
SET search_path = pg_catalog
AS $$
    SELECT (value = 'UTC' OR position('/' in value) > 0)
       AND value NOT LIKE 'posix/%' AND value NOT LIKE 'right/%'
       AND EXISTS (SELECT 1 FROM pg_catalog.pg_timezone_names WHERE name = value)
$$;

CREATE TABLE public.clinics (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    workspace_id bigint NOT NULL REFERENCES public.doctor_workspaces(id),
    name character varying(160) NOT NULL CHECK (length(btrim(name)) > 0),
    country character varying(100) NOT NULL CHECK (length(btrim(country)) > 0),
    province character varying(160) NOT NULL CHECK (length(btrim(province)) > 0),
    city character varying(160) NOT NULL CHECK (length(btrim(city)) > 0),
    address character varying(255) NOT NULL CHECK (length(btrim(address)) > 0),
    timezone character varying(100) NOT NULL CHECK (public.is_iana_timezone(timezone)),
    status character varying(16) NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE', 'INACTIVE', 'ARCHIVED')),
    version bigint NOT NULL DEFAULT 0 CHECK (version >= 0),
    created_at timestamp with time zone NOT NULL DEFAULT now(),
    updated_at timestamp with time zone NOT NULL DEFAULT now(),
    CONSTRAINT clinics_timestamps_check CHECK (updated_at >= created_at)
);

-- Supports owner-scoped listing and FK checks without commercial semantics.
CREATE INDEX clinics_workspace_status_idx ON public.clinics(workspace_id, status, id);
